import { existsSync, readFileSync } from "node:fs";
import { basename, join, posix } from "node:path";
import fg from "fast-glob";
import { parseToml } from "./toml.js";

export interface PythonDependency {
  /** Distribution name as written. */
  name: string;
  line?: number;
  /** Pinned to one version (`==`). */
  pinned?: boolean;
}

export interface PythonManifest {
  /** Path relative to the project root, e.g. `backend/requirements.txt`. */
  path: string;
  dependencies: PythonDependency[];
}

export interface PythonEntryPoint {
  /** `module.path` or `module.path:attr`. */
  target: string;
  /** Where it was declared, e.g. `pyproject.toml#project.scripts.app`. */
  source: string;
}

export interface PythonProject {
  /** Directory relative to the repository root ("" for the root). */
  dir: string;
  name: string;
  /** Manifests listing production dependencies. */
  manifests: PythonManifest[];
  entryPoints: PythonEntryPoint[];
  /** Built and published as a package (not an app): its public modules are its API. */
  library: boolean;
  /** Extra package directories relative to `dir`, such as maturin's `python-source` or setuptools' `where`. */
  sourceDirs: string[];
  /** Raw text of config sections that may name plugins (pyproject, setup.cfg). */
  configText: string;
}

const IGNORE = [
  "**/node_modules/**",
  "**/.git/**",
  "**/.venv/**",
  "**/venv/**",
  "**/.tox/**",
  "**/.nox/**",
  "**/site-packages/**",
  "**/dist/**",
  "**/build/**",
  "**/vendor/**",
  "**/fixtures/**",
  "**/__fixtures__/**",
];
const ANCHORS = ["pyproject.toml", "setup.py", "setup.cfg", "Pipfile", "manage.py", "requirements.txt", "requirements.in", "requirements*.txt", "requirements/*.txt"];
const APP_SIGNALS = ["manage.py", "Procfile", "app.yaml", "fly.toml", "render.yaml", "vercel.json", "serverless.yml", "serverless.yaml"];
/** Requirement files for development, tests, docs, or CI rather than production. */
const DEV_REQUIREMENTS = /(^|[-_./])(dev|develop|development|test|tests|testing|lint|linting|docs?|ci|local|tox|mypy|typing|types|style|format|qa|bench|benchmarks?|optional|extras?|build|tools?)([-_.]|$)/i;

export function discoverPythonProjects(root: string): PythonProject[] {
  const patterns = ["", "*/", "*/*/", "*/*/*/"].flatMap((depth) => ANCHORS.map((a) => depth + a));
  const anchors = fg.sync(patterns, { cwd: root, ignore: IGNORE, onlyFiles: true });
  const dirs = new Set<string>();
  for (const rel of anchors) {
    let dir = posix.dirname(rel);
    if (posix.basename(dir) === "requirements" && rel.endsWith(".txt")) dir = posix.dirname(dir);
    dirs.add(dir === "." ? "" : dir);
  }
  return [...dirs].sort().map((dir) => readProject(root, dir));
}

function readProject(root: string, dir: string): PythonProject {
  const abs = join(root, dir);
  const read = (name: string) => {
    const file = join(abs, name);
    try {
      return existsSync(file) ? readFileSync(file, "utf8") : undefined;
    } catch {
      return undefined;
    }
  };
  const rel = (name: string) => (dir ? `${dir}/${name}` : name);
  const project: PythonProject = { dir, name: "", manifests: [], entryPoints: [], library: false, sourceDirs: [], configText: "" };

  const pyprojectText = read("pyproject.toml");
  const pyproject = pyprojectText ? parseToml(pyprojectText) : undefined;
  if (pyproject && pyprojectText) readPyproject(project, pyproject, pyprojectText, rel("pyproject.toml"));
  if (pyproject) {
    const tool = (pyproject.tool ?? {}) as Record<string, any>;
    const where = tool.setuptools?.packages?.find?.where;
    for (const d of [tool.maturin?.["python-source"], ...(Array.isArray(where) ? where : [where])]) {
      if (typeof d === "string" && d && d !== "." && d !== "src") project.sourceDirs.push(d.replace(/^\.\//, "").replace(/\/$/, ""));
    }
  }

  const setupPy = read("setup.py");
  if (setupPy) readSetupPy(project, setupPy, rel("setup.py"));
  const setupCfg = read("setup.cfg");
  if (setupCfg) readSetupCfg(project, setupCfg, rel("setup.cfg"));

  const pipfile = read("Pipfile");
  if (pipfile) {
    const packages = (parseToml(pipfile).packages ?? {}) as Record<string, unknown>;
    project.manifests.push({ path: rel("Pipfile"), dependencies: Object.keys(packages).map((name) => ({ name, line: lineOf(pipfile, name) })) });
  }

  const requirementFiles = fg.sync(["requirements*.txt", "requirements/*.txt"], { cwd: abs, onlyFiles: true }).sort();
  for (const file of requirementFiles) {
    if (DEV_REQUIREMENTS.test(basename(file, ".txt").replace(/^requirements/, "")) || DEV_REQUIREMENTS.test(posix.dirname(file) === "requirements" ? basename(file, ".txt") : "")) continue;
    let text = read(file) ?? "";
    // Lock files (pip-compile, uv) list every transitive package; read the source list instead.
    if (/autogenerated by (pip-compile|uv)|^\s+# via /m.test(text)) {
      const source = read(file.replace(/\.txt$/, ".in"));
      if (!source) continue;
      text = source;
    }
    const dependencies = parseRequirements(text);
    // `pip freeze` output pins every installed package, direct or not, so unused ones cannot be told apart.
    if (dependencies.length >= 10 && dependencies.every((d) => d.pinned)) continue;
    project.manifests.push({ path: rel(file), dependencies });
  }
  if (!requirementFiles.length) {
    const source = read("requirements.in");
    if (source) project.manifests.push({ path: rel("requirements.in"), dependencies: parseRequirements(source) });
  }

  const packaged =
    (!!pyproject && (!!pyproject["build-system"] || !!(pyproject.tool as Record<string, unknown> | undefined)?.poetry)) || !!setupPy || !!setupCfg;
  const appSignal =
    APP_SIGNALS.some((name) => existsSync(join(abs, name))) ||
    fg.sync(["Dockerfile*", "docker-compose*.y*ml", "compose.y*ml"], { cwd: abs, onlyFiles: true }).length > 0 ||
    /package-mode\s*=\s*false|^\s*package\s*=\s*false/m.test(pyprojectText ?? "");
  project.library = packaged && !appSignal;
  if (!project.name) project.name = dir ? posix.basename(dir) : "";
  return project;
}

function readPyproject(project: PythonProject, doc: Record<string, unknown>, text: string, path: string): void {
  const meta = (doc.project ?? {}) as Record<string, unknown>;
  const tool = (doc.tool ?? {}) as Record<string, unknown>;
  const poetry = (tool.poetry ?? {}) as Record<string, unknown>;
  project.name = (typeof meta.name === "string" && meta.name) || (typeof poetry.name === "string" && poetry.name) || "";
  const deps: PythonDependency[] = [];
  for (const spec of Array.isArray(meta.dependencies) ? meta.dependencies : []) {
    const name = requirementName(String(spec));
    if (name) deps.push({ name, line: lineOf(text, String(spec)) });
  }
  for (const name of Object.keys((poetry.dependencies ?? {}) as object)) {
    if (name.toLowerCase() !== "python") deps.push({ name, line: lineOf(text, name) });
  }
  if (deps.length) project.manifests.push({ path, dependencies: deps });

  const scripts: Array<[string, Record<string, unknown> | undefined]> = [
    ["project.scripts", meta.scripts as Record<string, unknown>],
    ["project.gui-scripts", meta["gui-scripts"] as Record<string, unknown>],
    ["tool.poetry.scripts", poetry.scripts as Record<string, unknown>],
  ];
  for (const [group, entries] of Object.entries((meta["entry-points"] ?? {}) as Record<string, Record<string, unknown>>)) scripts.push([`project.entry-points.${group}`, entries]);
  for (const [group, entries] of Object.entries((poetry.plugins ?? {}) as Record<string, Record<string, unknown>>)) scripts.push([`tool.poetry.plugins.${group}`, entries]);
  for (const [section, entries] of scripts) {
    for (const [name, value] of Object.entries(entries ?? {})) {
      const target = typeof value === "string" ? value : typeof (value as Record<string, unknown>)?.callable === "string" ? ((value as Record<string, unknown>).callable as string) : undefined;
      if (target) project.entryPoints.push({ target: target.replace(/\s*\[.*\]$/, "").trim(), source: `${path}#${section}.${name}` });
    }
  }
  // Tool sections name plugins and modules as strings (`plugins = ["pydantic.mypy"]`).
  project.configText += text.slice(text.indexOf("[tool")) + "\n";
}

function readSetupPy(project: PythonProject, text: string, path: string): void {
  if (!project.name) project.name = /\bname\s*=\s*["']([^"']+)["']/.exec(text)?.[1] ?? "";
  const requires = /install_requires\s*=\s*\[([^\]]*)\]/.exec(text);
  if (requires) {
    const deps: PythonDependency[] = [];
    for (const m of requires[1]!.matchAll(/["']([^"']+)["']/g)) {
      const name = requirementName(m[1]!);
      if (name) deps.push({ name, line: lineOf(text, m[1]!) });
    }
    if (deps.length) project.manifests.push({ path, dependencies: deps });
  }
  for (const m of text.matchAll(/["']\s*([\w.-]+)\s*=\s*([\w.]+:[\w.]+)\s*(?:\[[^\]]*\])?\s*["']/g)) {
    project.entryPoints.push({ target: m[2]!, source: `${path}#entry_points.${m[1]}` });
  }
}

function readSetupCfg(project: PythonProject, text: string, path: string): void {
  const sections = iniSections(text);
  const options = sections.get("metadata");
  if (!project.name && options?.get("name")) project.name = options.get("name")!.trim();
  const requires = sections.get("options")?.get("install_requires");
  if (requires) {
    const deps = requires
      .split("\n")
      .map((line) => requirementName(line))
      .filter((n): n is string => !!n)
      .map((name) => ({ name, line: lineOf(text, name) }));
    if (deps.length) project.manifests.push({ path, dependencies: deps });
  }
  for (const [group, value] of sections.get("options.entry_points") ?? []) {
    for (const line of value.split("\n")) {
      const m = /^\s*([\w.-]+)\s*=\s*([\w.]+(?::[\w.]+)?)/.exec(line);
      if (m) project.entryPoints.push({ target: m[2]!, source: `${path}#options.entry_points.${group}.${m[1]}` });
    }
  }
  project.configText += text + "\n";
}

function iniSections(text: string): Map<string, Map<string, string>> {
  const out = new Map<string, Map<string, string>>();
  let section: Map<string, string> | undefined;
  let key: string | undefined;
  for (const raw of text.split(/\r?\n/)) {
    if (/^\s*[#;]/.test(raw)) continue;
    const header = /^\[([^\]]+)\]/.exec(raw);
    if (header) {
      section = new Map();
      out.set(header[1]!.trim(), section);
      key = undefined;
      continue;
    }
    if (!section) continue;
    const kv = /^([\w.-]+)\s*[=:]\s*(.*)$/.exec(raw);
    if (kv) {
      key = kv[1]!;
      section.set(key, kv[2]!);
    } else if (key && /^\s+\S/.test(raw)) {
      section.set(key, `${section.get(key)}\n${raw.trim()}`);
    }
  }
  return out;
}

/** Distribution names from a requirements file. Options, includes, and editable installs are skipped. */
export function parseRequirements(text: string): PythonDependency[] {
  const out: PythonDependency[] = [];
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!.replace(/(^|\s)#.*$/, "").trim();
    if (!line || line.startsWith("-")) continue;
    const name = requirementName(line);
    if (name) out.push({ name, line: i + 1, pinned: /===?/.test(line) });
  }
  return out;
}

/** The distribution in a PEP 508 requirement: `requests[socks]>=2 ; python_version > "3"` -> requests. */
export function requirementName(spec: string): string | undefined {
  const trimmed = spec.trim();
  if (/^(https?:\/\/|git\+|file:|\.\.?\/|\/)/.test(trimmed)) return /#egg=([\w.-]+)/.exec(trimmed)?.[1];
  return /^([A-Za-z0-9][A-Za-z0-9._-]*)/.exec(trimmed)?.[1];
}

function lineOf(text: string, needle: string): number | undefined {
  const index = text.indexOf(needle);
  return index === -1 ? undefined : text.slice(0, index).split("\n").length;
}
